"""Regenerate src/tex/metrics.rs from the Computer Modern TFM files.
Needs a TeX installation with kpsewhich and tftopl on the path.
"""
from pathlib import Path
import re
import subprocess

KERNED = [('MAIN', 'cmr10'), ('BOLD', 'cmbx10'), ('ITALIC', 'cmti10'), ('SANS', 'cmss10')]
# The size each font file takes over from, as LaTeX's OT1 and OML .fd files select them.
FAMILIES = [
    ('ROMAN', 'cmr', [(0, 5), (6, 6), (7, 7), (8, 8), (9, 9), (10, 10), (12, 12), (17, 17)]),
    ('STRONG', 'cmbx', [(0, 5), (6, 6), (7, 7), (8, 8), (9, 9), (10, 10), (12, 12)]),
    ('SLANTED', 'cmti', [(0, 7), (8, 8), (9, 9), (10, 10), (12, 12)]),
    ('MATH', 'cmmi', [(0, 5), (6, 6), (7, 7), (8, 8), (9, 9), (10, 10), (12, 12)]),
    ('SYMBOLS', 'cmsy', [(0, 5), (6, 6), (7, 7), (8, 8), (9, 9), (10, 10)]),
    ('PLAIN', 'cmss', [(0, 8), (9, 9), (10, 10), (12, 12), (17, 17)]),
    ('MONO', 'cmtt', [(0, 8), (9, 9), (10, 10), (12, 12)]),
]
F_LIGATURES = range(0o13, 0o20)


def code(kind, value):
    return ord(value) if kind == 'C' else int(value, 8)


def property_list(name):
    path = subprocess.run(['kpsewhich', f'{name}.tfm'], capture_output=True, text=True, check=True).stdout.strip()
    return subprocess.run(['tftopl', path], capture_output=True, text=True, check=True).stdout


def widths_of(text):
    return {code(k, v): float(w) for k, v, w in re.findall(r'\(CHARACTER ([CO]) (\S+)\s+\(CHARWD R ([\d.-]+)\)', text)}


def pairs_of(name):
    text = property_list(name)
    widths = widths_of(text)
    body = text[text.index('(LIGTABLE'):]
    body = body[:body.index('\n   )')]
    pairs, labels = {}, []
    for line in body.splitlines():
        line = line.strip()
        label = re.match(r'\(LABEL ([CO]) (\S+)\)', line)
        lig = re.match(r'\(LIG ([CO]) (\S+) ([CO]) (\S+)\)', line)
        kern = re.match(r'\(KRN ([CO]) (\S+) R ([\d.-]+)\)', line)
        if label:
            # A label inside a program is one more entry point: everything
            # above it still runs on through what follows, up to the STOP.
            labels.append(code(*label.groups()))
        elif line.startswith('(STOP'):
            labels = []
        elif lig:
            right, result = code(lig[1], lig[2]), code(lig[3], lig[4])
            if result in F_LIGATURES:
                for left in labels:
                    adjust = widths[result] - widths[left] - widths[right]
                    pairs.setdefault((left, right), (round(adjust * 1000), result))
        elif kern:
            right = code(kern[1], kern[2])
            for left in labels:
                pairs.setdefault((left, right), (round(float(kern[3]) * 1000), right))
    return sorted((l, r, a, n) for (l, r), (a, n) in pairs.items())


def design(stem, start, size):
    text = property_list(f'{stem}{size}')
    widths = widths_of(text)
    row = ','.join(str(round(widths.get(c, 0) * 1000)) for c in range(128))
    dimen = lambda key: round(float((re.search(rf'\({key} R ([\d.-]+)\)', text) or [0, 0])[1]) * 1000)
    space = (dimen('SPACE'), dimen('STRETCH'), dimen('SHRINK'), dimen('EXTRASPACE'))
    return f'Design {{ from: {start}, space: {space}, widths: [{row}] }}'


out = [
    '// Generated by assets/metrics.py from the Computer Modern TFM files.',
    '// A pair is (left, right, adjustment, state): the OT1 codes of two characters,',
    '// the change in width they bring, and the code the next pair starts from, which',
    '// differs from right only when the two form a ligature.',
    'type Pair = (u8, u8, i16, u8);',
    '',
    '/// One font file: the size in points it takes over from, its interword space',
    '/// as width, stretch, shrink and extra, and its widths by character code.',
    'pub(super) struct Design {',
    '    pub(super) from: u16,',
    '    pub(super) space: (i32, i32, i32, i32),',
    '    pub(super) widths: [i16; 128],',
    '}',
    '',
]
for constant, name in KERNED:
    rows = pairs_of(name)
    out.append('#[rustfmt::skip]')
    out.append(f'pub(super) const {constant}: &[Pair] = &[' + ','.join(f'({l},{r},{a},{n})' for l, r, a, n in rows) + '];')
for constant, stem, sizes in FAMILIES:
    out.append('#[rustfmt::skip]')
    out.append(f'pub(super) const {constant}: &[Design] = &[' + ','.join(design(stem, start, size) for start, size in sizes) + '];')
Path(__file__).resolve().parent.parent.joinpath('src/tex/metrics.rs').write_text('\n'.join(out) + '\n')
